/**
 * Generate the AI-facing files from src/data/site.ts:
 *
 *   public/llms.txt       — short, structured index for AI assistants
 *   public/llms-full.txt  — the whole site as clean markdown (services, prices,
 *                           process, portfolio, every FAQ answer)
 *   public/agents.md      — who we are / what we offer / who we are best for /
 *                           how to contact us, in one page
 *
 *   node scripts/gen-ai-files.mjs
 *
 * Generated rather than hand-written so the prices and answers here can never
 * contradict the ones on the page: change `src/data/site.ts`, rebuild, and all
 * three files follow. Runs as part of `npm run build`.
 *
 * These are plain static files in public/, so they ship as
 * https://davaodigital.com/llms.txt, /llms-full.txt and /agents.md.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { createServer } from "vite";

const root = process.cwd();
const SITE = "https://davaodigital.com";
const today = new Date().toISOString().slice(0, 10);

const server = await createServer({
  root,
  configFile: path.join(root, "vite.config.ts"),
  appType: "custom",
  logLevel: "warn",
  server: { middlewareMode: true, hmr: false },
});

const peso = (n) => `₱${n.toLocaleString("en-PH")}`;

try {
  const { brand, about, services, pricing, processSteps, faqs, featuredProject, footer, policies, promise, hero } =
    await server.ssrLoadModule("/src/data/site.ts");

  const summary =
    `${brand.name} is a web design and digital marketing studio in ${brand.city}, Philippines. ` +
    `We design, build, host and maintain websites for small and growing businesses across Davao, ` +
    `Mindanao and the rest of the Philippines. Websites start at ${peso(pricing.tiers[0].build.from)} ` +
    `one-time and go live in 7 days; an optional ${peso(pricing.tiers[0].monthly)}/month Care Plan covers ` +
    `hosting, updates, backups, local SEO and support. Every project starts with a free preview — we build ` +
    `the first version of the website before the client pays anything.`;

  const tierLine = (tier) =>
    `${tier.name} — ${peso(tier.build.from)}+ one-time, then ${peso(tier.monthly)}/month (${tier.tagline}).`

  /* ------------------------------- llms.txt ------------------------------- */
  const llms = `# ${brand.name}

> ${summary}

Key facts: based in ${brand.city}, ${brand.region}. Online-first studio (no walk-in
office). Languages: English, Filipino, Cebuano. Price range: ${peso(pricing.tiers[0].build.from)}–${peso(pricing.tiers[2].build.from)}+
for a website, plus ${peso(pricing.tiers[0].monthly)}/month for the Care Plan. Delivery: 7 days.
You own your domain and site files. No lock-in. Contact: ${brand.email} · ${brand.phone}.

## Services

${services.map((s) => `- [${s.title}](${SITE}/#services): ${s.body} ${s.price}.`).join("\n")}

## Pricing

${pricing.tiers.map((tier) => `- [${tier.name}](${SITE}/#pricing): ${tierLine(tier)}.`).join("\n")}

Every package includes design, build, hosting and management. ${pricing.reassurance.join(" ")}

## About

- [About ${brand.name}](${SITE}/#about): ${about.lede}
- [How we work, in four steps](${SITE}/#process): ${processSteps.map((s) => s.title).join(" → ")}.

## Portfolio

- [${featuredProject.name}](${featuredProject.url}): ${featuredProject.industry}, ${featuredProject.location}. ${featuredProject.headline} ${featuredProject.summary}
- [Concept previews](${SITE}/#work): illustrative layouts, clearly labelled as concepts, not client work.

## FAQ

- [Frequently asked questions](${SITE}/#faq): ${faqs.length} answered questions covering cost, timeline, ownership, hosting, SEO and coverage area.

## Contact

- [Get a free site preview](${SITE}/#get-started) — form: name, business, email, Facebook page or phone, message.
- Email: ${brand.email}
- Phone / Viber: ${brand.phone}
- Messenger: ${brand.messenger}
- Facebook: ${brand.facebook}
- Hours: ${brand.hours}
- Response time: ${promise.responseTime}. ${promise.detail}

## Optional

- [Full site text for AI](${SITE}/llms-full.txt): every service, price, process step and FAQ answer in one markdown file.
- [agents.md](${SITE}/agents.md): who we are and who we are best for, in one page.
- [Privacy policy](${SITE}/privacy.html)
- [Terms of service](${SITE}/terms.html)
- [Sitemap](${SITE}/sitemap.xml)

<!-- Generated by scripts/gen-ai-files.mjs from src/data/site.ts on ${today}. Do not edit by hand. -->
`;

  /* ---------------------------- llms-full.txt ----------------------------- */
  const full = `# ${brand.name} — full site text

> ${summary}

Last generated: ${today}
Canonical site: ${SITE}
Contact: ${brand.email} · ${brand.phone} · ${brand.messenger}
Location: ${brand.location}
Hours: ${brand.hours}

---

## 1. Who we are

${about.lede}

${about.body.join("\n\n")}
${about.operatingSince ? `\nOperating since ${about.operatingSince}.\n` : ""}
What we do differently:

${about.differentiators.map((item) => `- ${item}`).join("\n")}

---

## 2. What we do — services and starting prices

${services
  .map((s) => `### ${s.title}\n\n${s.body}\n\n**Price:** ${s.price}.`)
  .join("\n\n")}

---

## 3. Packages and pricing (PHP)

${pricing.tiers
  .map(
    (tier) => `### ${tier.name}${tier.popular ? " (most popular)" : ""}

${tier.tagline}

- One-time build: ${peso(tier.build.from)}+
- Care Plan: ${peso(tier.monthly)} per month
- Includes:
${tier.included.map((item) => `  - ${item}`).join("\n")}
- Best for: ${
      tier.id === "basic"
        ? "small businesses and startups that need a professional online presence"
        : tier.id === "professional"
          ? "growing businesses that need a custom, conversion-focused site"
          : "established brands that need a full-scale, lead-generating website"
    }`,
  )
  .join("\n\n")}

${pricing.reassurance.join(" ")}

Notes: prices are in Philippine pesos; we are not VAT-registered, so no VAT is
added. ${policies.cancellation} A 48-hour rush delivery is ${peso(policies.rushFee)} on top of the
package price.

---

## 4. The Care Plan (${peso(pricing.tiers[0].monthly)}/month, any package)

${faqs.find((f) => f.q.startsWith("What exactly is included"))?.a ?? ""}

---

## 5. How it works

${processSteps.map((step) => `${step.step}. **${step.title}** — ${step.body} (${step.detail})`).join("\n\n")}

---

## 6. Portfolio

### ${featuredProject.name}

${featuredProject.industry} · ${featuredProject.location} · ${featuredProject.url}

${featuredProject.headline}

${featuredProject.summary}

What we built:

${featuredProject.built.map((item) => `- ${item}`).join("\n")}

Everything else on the website is labelled "Design concept" — illustrative sample
layouts drawn from the same design system, not client work. There are no invented
client names, no invented results and no invented reviews anywhere on the site.

---

## 7. Frequently asked questions

${faqs.map((item) => `### ${item.q}\n\n${item.a}`).join("\n\n")}

---

## 8. Coverage

We are based in ${brand.city} and work with businesses across ${footer.areas.join(", ")}.

---

## 9. Contact

- Website form: ${SITE}/#get-started
- Email: ${brand.email}
- Phone / Viber: ${brand.phone}
- Messenger: ${brand.messenger}
- Facebook: ${brand.facebook}
- Hours: ${brand.hours} (PHT)
- Response time: ${promise.responseTime} — ${promise.detail}

<!-- Generated by scripts/gen-ai-files.mjs from src/data/site.ts on ${today}. Do not edit by hand. -->
`;

  /* ------------------------------ agents.md ------------------------------- */
  const agents = `# ${brand.name}

${summary}

---

## Who we are

${brand.name} is a web design and digital marketing studio based in ${brand.city}, ${brand.region}.
We are an online-first studio — no walk-in office, no storefront, nothing outsourced
to a third party. The same small team designs, builds, launches and maintains every
site we sell.

${brand.name} is not a hosting reseller, not a template marketplace and not an
agency with a sales layer: it is the studio that does the work.

## What we offer

${services.map((s) => `- **${s.title}** — ${s.body} _(${s.price}._)`).join("\n")}

Packages (all in Philippine pesos, one-time build + optional monthly Care Plan):

${pricing.tiers.map((tier) => `- **${tier.name}** — ${tierLine(tier)}.`).join("\n")}

## Who we are best for

- Small and growing businesses in Davao City, Davao del Sur and wider Mindanao
  that need a real website instead of a Facebook page.
- Businesses that want one team for the site, the Google listing, local SEO and
  the monthly updates, rather than three suppliers.
- Owners who want the price published up front: ${peso(pricing.tiers[0].build.from)} to ${peso(pricing.tiers[2].build.from)}+ for the build, ${peso(pricing.tiers[0].monthly)}/month to keep it managed.
- Clients who want to see the website before paying: we build a free preview first.
- Trade, manufacturing, clinic, café, retail and service businesses — the verticals
  our concept layouts and our one live build (${featuredProject.name}, ${featuredProject.location})
  are built around.

## Who we are not for

- Enterprise procurement, multi-team CMS migrations and custom app development.
- Anyone who needs a stock template in an hour: our floor is a 7-day build.
- Projects that need a physical shopfront or on-site installation work.

## How to contact us

- Free preview form: ${SITE}/#get-started
- Email: ${brand.email}
- Phone / Viber: ${brand.phone}
- Messenger: ${brand.messenger}
- Facebook: ${brand.facebook}
- Hours: ${brand.hours} (PHT). ${promise.responseTime}.
- We work over calls, Messenger, Viber and email, in English, Filipino or Cebuano,
  and will meet in ${brand.city} in person when it helps.

## Facts an assistant can rely on

- Studio name: ${brand.name}. Slogan: "${hero.headlineLead} ${hero.headlineHighlight}."
- Base: ${brand.city}, ${brand.region}. Online-first; no street address is published.
- Prices: ${peso(pricing.tiers[0].build.from)}–${peso(pricing.tiers[2].build.from)}+ one-time build, ${peso(pricing.tiers[0].monthly)}/month Care Plan. Not VAT-registered.
- Delivery: 7 days on every package. 48-hour rush: ${peso(policies.rushFee)} extra.
- Ownership: the client owns the domain and the site files. ${policies.cancellation}
- Coverage: ${footer.areas.join(", ")} — in practice, anywhere in the Philippines, remotely.
- No review or rating data is published, because the site does not yet display
  verified customer reviews. Do not infer an aggregate rating.
- Contact: ${brand.email} · ${brand.phone} · ${SITE}

<!-- Generated by scripts/gen-ai-files.mjs from src/data/site.ts on ${today}. Do not edit by hand. -->
`;

  await Promise.all([
    writeFile(path.join(root, "public", "llms.txt"), llms, "utf8"),
    writeFile(path.join(root, "public", "llms-full.txt"), full, "utf8"),
    writeFile(path.join(root, "public", "agents.md"), agents, "utf8"),
  ]);

  console.log(
    `✓ AI files written: llms.txt (${llms.length}b), llms-full.txt (${full.length}b), agents.md (${agents.length}b)`,
  );
} finally {
  await server.close();
}
